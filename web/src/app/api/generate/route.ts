function todayET(): string {
  const now = new Date();
  const et = new Date(now.toLocaleString("en-US", { timeZone: "America/New_York" }));
  return et.toISOString().split("T")[0];
}

function normalizePosition(pos: string): string {
  if (pos === "SP" || pos === "RP") return "P";
  return pos;
}

// Per-team matchup map for a slate date, keyed by canonical DK abbr.
// std_game_context stores home/away teams (sometimes as full names — toDkAbbr
// normalizes), so for each team we can recover its opponent + home/away.
async function fetchMatchupMap(
  date: string,
): Promise<Map<string, { opp: string; isHome: boolean }>> {
  const out = new Map<string, { opp: string; isHome: boolean }>();
  const { data } = await supabase
    .from("std_game_context")
    .select("home_team, away_team")
    .eq("date", date);
  for (const g of (data as Array<Record<string, unknown>>) || []) {
    const home = canonDkTeam(toDkAbbr(String(g.home_team || "")));
    const away = canonDkTeam(toDkAbbr(String(g.away_team || "")));
    if (!home || !away) continue;
    out.set(home, { opp: away, isHome: true });
    out.set(away, { opp: home, isHome: false });
  }
  return out;
}

// FanDuel display slots (the 8 fixed slots; the 9th is UTIL flex). The
// fd-optimizer assigns each selected player a single concrete position
// (P/C/1B/2B/3B/SS/OF), so two 1B both literally read "1B". To surface the
// UTIL slot the way FD does, greedily fill the fixed slots and return the
// index of the one player that overflows — that player is the UTIL.
const FD_FIXED_SLOTS = ["P", "C/1B", "2B", "3B", "SS", "OF", "OF", "OF"] as const;
function fdSlotAccepts(slot: string, pos: string): boolean {
  if (slot === pos) return true;
  if (slot === "C/1B") return pos === "C" || pos === "1B";
  return false;
}
function fdUtilIndex(positions: string[]): number {
  const taken = new Array(FD_FIXED_SLOTS.length).fill(false);
  let utilIdx = -1;
  positions.forEach((pos, i) => {
    const p = normalizePosition(pos);
    let placed = false;
    for (let s = 0; s < FD_FIXED_SLOTS.length; s++) {
      if (taken[s]) continue;
      if (fdSlotAccepts(FD_FIXED_SLOTS[s], p)) {
        taken[s] = true;
        placed = true;
        break;
      }
    }
    if (!placed) utilIdx = i;
  });
  return utilIdx;
}

// Mirror of mlb/src/gpp_v2/name_norm.py — keeps cross-source joins resilient
// to accents, casing, suffixes, periods, whitespace.
function normalizeName(s: string | null | undefined): string {
  if (!s) return "";
  let n = s.normalize("NFD").replace(/[\u0300-\u036f]/g, "");
  n = n.toLowerCase();
  n = n.replace(/\s+(jr|sr|ii|iii|iv)\.?$/i, "");
  n = n.replace(/\./g, "");
  return n.replace(/\s+/g, " ").trim();
}

// (team, last_name) fallback for nickname mismatches — Joseph↔Joey,
// William↔Will, Robert↔Bobby. Ambiguous keys (same last on same team)
// are skipped at build time to avoid silent cross-attribution.
function lastTeamKey(name: string | null | undefined, team: string | null | undefined): string {
  const norm = normalizeName(name);
  if (!norm) return "";
  const parts = norm.split(" ");
  const last = parts[parts.length - 1] || "";
  if (!last) return "";
  return `${(team || "").toUpperCase()}|${last}`;
}

